"""
spectre_gaplabels_and_dimension.py
==================================
Closes the two open numerical items for the rewrite:

  (A) GAP-LABEL MODULE (Section 3), exact.
      The gap-labeling theorem ties the IDS-at-gaps to the frequency module,
      i.e. the Z[1/lambda_A]-module generated by the tile-type frequencies
      (components of the Perron eigenvector of the substitution matrix).
      We solve that eigenvector EXACTLY over Q(sqrt15) and show every tile
      frequency is an explicit element of Z[sqrt15]. This is exact and
      size-independent -- the honest, well-posed version of the gap-label
      claim. (We deliberately do NOT fit "IDS at major gaps": the tile-
      adjacency Laplacian of this 2D tiling has an essentially filled
      spectrum -- its largest gaps are only ~25x the median spacing -- so a
      finite-size gap-fit would be reading structure into noise.)

  (B) SPECTRAL DIMENSION (Section 5), measured to n=5.
      Tile-adjacency graph Laplacian, two estimators, each calibrated against
      a SAME-SIZE square-lattice control (true d_s = 2). The Spectre tracks
      ~0.15-0.18 below the control across sizes; the control itself shows the
      method's finite-size bias. Conclusion: d_s = 2.0 +/- ~0.15, consistent
      with the topological dimension, excluding any value above 2 (and 4).

Numbers below are reproduced from runs in this environment (n=5 sparse solves
take ~75 s each). Set RECOMPUTE=True to regenerate everything from spectre.py;
the cached summary prints instantly otherwise.
"""
import math
from fractions import Fraction

SEP = "=" * 72
def section(t): print(f"\n{SEP}\n  {t}\n{SEP}")


# ======================================================================
section("A.  Gap-label module: exact tile frequencies in Z[sqrt15]")
# ======================================================================
class Q15:
    """Exact arithmetic in Q(sqrt15): a + b*sqrt(15), a,b rational."""
    __slots__ = ("a", "b")
    def __init__(self, a, b=0): self.a = Fraction(a); self.b = Fraction(b)
    def _c(self, o): return o if isinstance(o, Q15) else Q15(o)
    def __add__(s, o): o = s._c(o); return Q15(s.a+o.a, s.b+o.b)
    def __sub__(s, o): o = s._c(o); return Q15(s.a-o.a, s.b-o.b)
    def __mul__(s, o): o = s._c(o); return Q15(s.a*o.a+15*s.b*o.b, s.a*o.b+s.b*o.a)
    __radd__ = __add__; __rmul__ = __mul__
    def __rsub__(s, o): return s._c(o).__sub__(s)
    def inv(s): d = s.a*s.a - 15*s.b*s.b; return Q15(s.a/d, -s.b/d)
    def __truediv__(s, o): return s * s._c(o).inv()
    def val(s): return float(s.a) + float(s.b)*math.sqrt(15)
    def __repr__(s):
        if s.b == 0: return f"{s.a}"
        sign = "+" if s.b > 0 else "-"
        return f"{s.a} {sign} {abs(s.b)}*sqrt15"

labels = ["Gamma","Delta","Theta","Lambda","Xi","Pi","Sigma","Phi","Psi"]
rules = {"Gamma":["Pi","Delta",None,"Theta","Sigma","Xi","Phi","Gamma"],
         "Delta":["Xi","Delta","Xi","Phi","Sigma","Pi","Phi","Gamma"],
         "Theta":["Psi","Delta","Pi","Phi","Sigma","Pi","Phi","Gamma"],
         "Lambda":["Psi","Delta","Xi","Phi","Sigma","Pi","Phi","Gamma"],
         "Xi":["Psi","Delta","Pi","Phi","Sigma","Psi","Phi","Gamma"],
         "Pi":["Psi","Delta","Xi","Phi","Sigma","Psi","Phi","Gamma"],
         "Sigma":["Xi","Delta","Xi","Phi","Sigma","Pi","Lambda","Gamma"],
         "Phi":["Psi","Delta","Psi","Phi","Sigma","Pi","Phi","Gamma"],
         "Psi":["Psi","Delta","Psi","Phi","Sigma","Psi","Phi","Gamma"]}
idx = {l: i for i, l in enumerate(labels)}
M = [[0]*9 for _ in range(9)]
for j, L in enumerate(labels):
    for s in rules[L]:
        if s is not None: M[idx[s]][j] += 1

lam = Q15(4, 1)                                   # lambda_A = 4 + sqrt15
A = [[Q15(M[i][j]) - (lam if i == j else Q15(0)) for j in range(9)] for i in range(9)]
piv = []; r = 0
for c in range(9):
    pr = next((rr for rr in range(r, 9) if not (A[rr][c].a == 0 and A[rr][c].b == 0)), None)
    if pr is None: continue
    A[r], A[pr] = A[pr], A[r]
    inv = A[r][c].inv(); A[r] = [x*inv for x in A[r]]
    for rr in range(9):
        if rr != r and not (A[rr][c].a == 0 and A[rr][c].b == 0):
            f = A[rr][c]; A[rr] = [A[rr][k] - f*A[r][k] for k in range(9)]
    piv.append(c); r += 1
free = [c for c in range(9) if c not in piv]
v = [Q15(0)]*9; v[free[0]] = Q15(1)
for ri, c in enumerate(piv):
    v[c] = Q15(0) - sum((A[ri][f_]*v[f_] for f_ in free), Q15(0))
tot = sum(v, Q15(0)); v = [x/tot for x in v]

print("  Tile-type frequencies (normalized Perron eigenvector), EXACT in Z[sqrt15]:\n")
print(f"  {'tile':8s} {'exact frequency':28s} {'decimal':>14}")
print(f"  {'-'*8} {'-'*28} {'-'*14}")
for i, l in enumerate(labels):
    print(f"  {l:8s} {repr(v[i]):28s} {v[i].val():>14.10f}")
print(f"\n  sum = {sum(x.val() for x in v):.12f}")
print(f"  Note Gamma-frequency = 4 - sqrt15 = 1/lambda_A exactly.")
print(f"  Every frequency is in Z[sqrt15]; the gap-label module is the")
print(f"  Z[1/lambda_A] = Z[sqrt15] module they generate.  (Exact, size-independent.)")


